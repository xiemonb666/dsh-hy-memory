export const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = {
  en,
  'zh-CN': zhCN,
}

export type TranslateVars = Record<string, string | number | undefined>

export type Translate = (key: MessageKey, vars?: TranslateVars) => string

/**
 * Interpolate `{name}` placeholders. Missing vars are left as-is so a bug is
 * visible rather than silently rendering an empty string.
 */
export function interpolate(template: string, vars?: TranslateVars): string {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = vars[key]
    return value === undefined ? match : String(value)
  })
}

export function createTranslator(locale: Locale): Translate {
  const dictionary = DICTIONARIES[locale] ?? en
  return (key, vars) => interpolate(dictionary[key] ?? en[key] ?? key, vars)
}

/** Locale-aware number formatting with a stable fallback for missing values. */
export function formatNumber(value: number | undefined, locale: Locale): string {
  if (value === undefined || !Number.isFinite(value)) return '—'
  return new Intl.NumberFormat(locale === 'zh-CN' ? 'zh-CN' : 'en-US').format(value)
}

/** Locale-aware date/time formatting; empty string when the Host sent nothing. */
export function formatDateTime(value: string | undefined, locale: Locale): string {
  if (!value) return '—'
  const parsed = new Date(value)
  if (Number.isNaN(parsed.getTime())) return value
  return new Intl.DateTimeFormat(locale === 'zh-CN' ? 'zh-CN' : 'en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(parsed)
}

/** Short relative age, e.g. `3h ago`. */
export function formatRelative(value: string | undefined, locale: Locale): string {
  if (!value) return '—'
  const parsed = new Date(value).getTime()
  if (Number.isNaN(parsed)) return value
  const deltaSeconds = Math.round((parsed - Date.now()) / 1000)
  const formatter = new Intl.RelativeTimeFormat(locale === 'zh-CN' ? 'zh-CN' : 'en-US', { numeric: 'auto' })
  const abs = Math.abs(deltaSeconds)
  if (abs < 60) return formatter.format(Math.round(deltaSeconds), 'second')
  if (abs < 3600) return formatter.format(Math.round(deltaSeconds / 60), 'minute')
  if (abs < 86_400) return formatter.format(Math.round(deltaSeconds / 3600), 'hour')
  if (abs < 2_592_000) return formatter.format(Math.round(deltaSeconds / 86_400), 'day')
  return formatter.format(Math.round(deltaSeconds / 2_592_000), 'month')
}

/** Percent formatting that never invents a value. */
export function formatPercent(value: number | undefined, locale: Locale): string {
  if (value === undefined || !Number.isFinite(value)) return '—'
  const ratio = value > 1 ? value / 100 : value
  return new Intl.NumberFormat(locale === 'zh-CN' ? 'zh-CN' : 'en-US', {
    style: 'percent',
    maximumFractionDigits: 1,
  }).format(ratio)
}
